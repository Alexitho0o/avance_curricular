import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {SpreadsheetFile,FileBlob} from '@oai/artifact-tool';
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'../..');
const dir=path.join(root,'06_validaciones/maqueta_etapa2_noviembre_20261023_v04');
const d=JSON.parse(await fs.readFile(path.join(dir,'INSUMOS.json'),'utf8'));
const wb=await SpreadsheetFile.importXlsx(await FileBlob.load(d.source));
const s=wb.worksheets.add('Diplomados vigencia 3');s.showGridLines=false;
s.getRange('A1:E22').format.font={name:'Arial',size:10,color:'#242424'};
s.getRange('A1:E22').format.verticalAlignment='center';
for(const [c,width] of [['A',14],['B',73],['C',18],['D',28],['E',83]])s.getRange(`${c}1:${c}22`).format.columnWidth=width;
s.getRange('A2').values=[['Diplomados cargados con vigencia 3: revision de Docencia']];
s.getRange('A2').format.font={name:'Arial',size:15,bold:true};
s.getRange('A3').values=[['Estos 14 programas SI fueron cargados y aceptados en Etapa 1, como NO VIGENTES. No son registros rechazados ni omitidos del archivo.']];
s.getRange('A4').values=[['Marcar SI pide evaluar una rectificacion: no cambia la vigencia en PES ni confirma que SIES acepte la solicitud.']];
s.getRange('A5').formulas=[['="Pendientes de respuesta: "&COUNTBLANK(D9:D22)&". Solicitan revision: "&COUNTIFS(D9:D22,"SI")&". Sin solicitud: "&COUNTIFS(D9:D22,"NO")&"."']];
s.getRange('A6:E6').values=[['Codigo aceptado. No modificar.','Nombre exacto cargado en V06. No modificar; describir cualquier correccion en la ultima columna.','3 = No vigente. No modificar.','Seleccione SI o NO. SI: pedir que se evalue una rectificacion. NO: no solicitarla.','Si marca SI, indique si debia estar vigente en 2027, el dato o nombre correcto, el motivo y el respaldo. Con NO, puede dejarlo vacio.']];
s.getRange('A6:E6').format={wrapText:true,rowHeight:70,fill:'#E7E6E6',font:{name:'Arial',size:10,color:'#242424'}};
s.getRange('D6:E6').format.fill='#FFF2CC';
s.getRange('A7').values=[['Fuente: CARGA_OFERTA_2027_ETAPA1_17467_20261023_V06.csv, version aceptada y congelada. Las dos columnas finales son solo de gestion interna.']];
s.getRange('A8:E22').values=[['COD_CARRERA','NOMBRE_CARRERA','VIGENCIA_CARRERA','Pedir rectificacion','Detalle de la solicitud'],...d.rows];
s.tables.add('A8:E22',true,'RevisionDiplomadosVigencia3').style='TableStyleLight1';
s.getRange('A8:E8').format={fill:'#3D4C59',font:{name:'Arial',size:10,color:'#FFFFFF',bold:true},wrapText:true,rowHeight:40,horizontalAlignment:'center'};
s.getRange('A9:E22').format={rowHeight:66,wrapText:true};
s.getRange('A9:C22').format.fill='#E7E6E6';
s.getRange('C9:C22').setNumberFormat('0');
s.getRange('D9:E22').format.fill='#FFF2CC';
s.getRange('D9:D22').dataValidation={rule:{type:'list',values:['SI','NO']}};
s.getRange('D9:D22').conditionalFormats.add('cellIs',{operator:'equal',formula:'"SI"',format:{fill:'#FFC7CE',font:{color:'#9C0006',bold:true}}});
s.getRange('D9:D22').conditionalFormats.add('cellIs',{operator:'equal',formula:'"NO"',format:{fill:'#E2EFDA'}});
s.getRange('E9:E22').conditionalFormats.addCustom('AND($D9="SI",LEN(E9&"")=0)',{fill:'#FFC7CE'});
s.freezePanes.freezeRows(8);s.freezePanes.freezeColumns(2);
wb.recalculate();
if(s.getRange('A5').values[0][0]!=='Pendientes de respuesta: 14. Solicitan revision: 0. Sin solicitud: 0.')throw Error('Conteo inicial');
s.getRange('D9').values=[['SI']];wb.recalculate();
if(s.getRange('A5').values[0][0]!=='Pendientes de respuesta: 13. Solicitan revision: 1. Sin solicitud: 0.')throw Error('Respuesta SI');
s.getRange('D9').clear({applyTo:'contents'});wb.recalculate();
const img=await wb.render({sheetName:s.name,range:'A2:E13',scale:1,format:'png'});
await fs.writeFile(path.join(dir,'REVISION_VISUAL.png'),new Uint8Array(await img.arrayBuffer()));
await(await SpreadsheetFile.exportXlsx(wb)).save(path.join(dir,'INTERMEDIO_V04.xlsx'));
console.log('Hoja de 14 diplomados creada; respuestas iniciales en blanco.');
